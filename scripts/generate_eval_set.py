def main():
    """Generate and save the eval set."""
    repo_root = Path(__file__).resolve().parent.parent
    eval_dir = repo_root / "data" / "eval"
    eval_dir.mkdir(parents=True, exist_ok=True)
    
    eval_path = eval_dir / "eval_set.json"
    with open(eval_path, "w", encoding="utf-8") as f:
        json.dump(EVAL_SET, f, indent=2, ensure_ascii=False)
    
    print(f"Generated eval set with {len(EVAL_SET)} questions")
    print(f"Saved to: {eval_path}")
    
    # Print summary
    domains = {}
    for q in EVAL_SET:
        d = q["domain_id"]
        domains[d] = domains.get(d, 0) + 1
    
    print("\nQuestions per domain:")
    for d, count in sorted(domains.items()):
        print(f"  {d}: {count}")


if __name__ == "__main__":
    main()
